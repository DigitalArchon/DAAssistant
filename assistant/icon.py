"""The application's own icon, and the search path that makes it findable by name.

Every tray backend takes an icon *name* and resolves it through the GTK icon theme, so a
PNG sitting in the source tree is not enough on its own: the directory holding it has to
be on the theme's search path before anything asks. Registering it here means one name
works identically from a git checkout, from the AppImage and from a system install, and
that the tray, the windows and the AppImage all show the same drawing.

The PNGs under data/icons are generated by packaging/make-icon.py and committed, so that
nothing has to be rendered at runtime and the bundle cannot drift from the app.
"""

import os

from . import gtkcompat  # noqa: F401  (pins GI versions)
from gi.repository import Gtk

NAME = "da-assistant"
# Used only if the bundled icons are missing, e.g. a partial install.
FALLBACK = "accessories-text-editor"

THEME_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "data", "icons")
SIZES = (16, 22, 24, 32, 48, 64, 128, 256)

_registered = False


def register():
    """Put the bundled icons on the default theme search path. Idempotent."""
    global _registered
    if not _registered and os.path.isdir(THEME_DIR):
        # A directory of icon *themes*, the same shape as /usr/share/icons.
        Gtk.IconTheme.get_default().append_search_path(THEME_DIR)
    _registered = True


def name():
    """The icon name to use, with the bundled icons registered first."""
    register()
    if Gtk.IconTheme.get_default().has_icon(NAME):
        return NAME
    return FALLBACK


def path(size=256):
    """Absolute path to the icon file at or above `size`, or None if unavailable.

    For the callers that want a file rather than a name: a desktop entry written by the
    user, where nothing has installed the icon into a system theme.
    """
    for candidate in sorted(SIZES, key=lambda s: (s < size, abs(s - size))):
        file = os.path.join(THEME_DIR, "hicolor", f"{candidate}x{candidate}",
                            "apps", f"{NAME}.png")
        if os.path.exists(file):
            return file
    return None
